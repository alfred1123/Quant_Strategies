-- Every source of a product is a row in PROVIDER_SUBSCR.
-- A venue's bars have no metric. A provider series has one.
-- The open row is unique on the id. Interval, product and source are
-- attributes of that id, not a second key.

ALTER TABLE MARKET_DATA.PROVIDER_SUBSCR
    ALTER COLUMN APP_METRIC_ID DROP NOT NULL;

DROP INDEX MARKET_DATA.UQ_PROVIDER_SUBSCR_OPEN;

-- Prod already has BAR_SUBSCRIPTION from the archived 1.3.0 release.
-- A database built from the current changelog does not, so the copy is conditional.
DO $migrate$
BEGIN
    IF to_regclass('market_data.bar_subscription') IS NOT NULL THEN
        INSERT INTO MARKET_DATA.PROVIDER_SUBSCR (
            PROVIDER_SUBSCR_ID,
            PROVIDER_SUBSCR_VID,
            INTERNAL_CUSIP,
            APP_ID,
            APP_METRIC_ID,
            TM_INTERVAL_ID,
            IS_ENABLED_IND,
            BACKFILL_FROM_TS,
            TRANSACT_FROM_TS,
            TRANSACT_TO_TS,
            CREATED_AT
        )
        SELECT BAR_SUBSCRIPTION_ID,
               BAR_SUBSCRIPTION_VID,
               INTERNAL_CUSIP,
               SOURCE_APP_ID,
               NULL,
               TM_INTERVAL_ID,
               IS_ENABLED_IND,
               BACKFILL_FROM_TS,
               TRANSACT_FROM_TS,
               TRANSACT_TO_TS,
               CREATED_AT
          FROM MARKET_DATA.BAR_SUBSCRIPTION;

        DROP TABLE MARKET_DATA.BAR_SUBSCRIPTION;
    END IF;
END
$migrate$;

DROP PROCEDURE IF EXISTS MARKET_DATA.SP_INS_BAR_SUBSCRIPTION(
    UUID, TEXT, INTEGER, INTEGER, CHAR(1), TIMESTAMPTZ, TEXT,
    OUT TEXT, OUT TEXT, OUT TEXT
);

DROP PROCEDURE IF EXISTS MARKET_DATA.SP_GET_BAR_SUBSCRIPTION(
    UUID, OUT REFCURSOR, OUT TEXT, OUT TEXT, OUT TEXT
);

DROP PROCEDURE IF EXISTS MARKET_DATA.SP_GET_ACTIVE_BAR_SUBSCRIPTIONS(
    OUT REFCURSOR, OUT TEXT, OUT TEXT, OUT TEXT
);

DROP PROCEDURE IF EXISTS MARKET_DATA.SP_GET_PROVIDER_SUBSCR(
    OUT REFCURSOR, OUT TEXT, OUT TEXT, OUT TEXT
);

ALTER TABLE MARKET_DATA.PROVIDER_SUBSCR RENAME TO SERIES_SUBSCR;
ALTER TABLE MARKET_DATA.SERIES_SUBSCR RENAME COLUMN PROVIDER_SUBSCR_ID TO SERIES_SUBSCR_ID;
ALTER TABLE MARKET_DATA.SERIES_SUBSCR RENAME COLUMN PROVIDER_SUBSCR_VID TO SERIES_SUBSCR_VID;
ALTER INDEX MARKET_DATA.UQ_PROVIDER_SUBSCR_ID_OPEN RENAME TO UQ_SERIES_SUBSCR_ID_OPEN;

